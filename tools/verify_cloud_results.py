#!/usr/bin/env python3
# File: tools/verify_cloud_results.py
# Purpose: Generate the canonical cloud-eval results table (counts + Wilson CIs) directly from
#          the raw promptfoo JSONs, and verify hand-maintained summaries against it.
# Project: sparkbench | Date: 2026-07-12
#
# Overview: The cloud results summary (e31-cloud-summary.md) was hand-transcribed and drifted
# from its own raw JSONs (+1 to +3 passes on five of six models), which nearly caused a correct
# whitepaper number to be "corrected" into a wrong one. This tool removes the drift class: it
# reads the raw per-model JSONs under results/deep-eval/, computes pass/total and a Wilson 95%
# score interval for each (no scipy dependency), and emits a canonical markdown table with a
# raw-file provenance column. `--check <file.md>` parses "| Name | passed | total | ..." rows in
# an existing summary and reports any row whose (passed,total) disagree with the raw JSON, so a
# summary can be gated in CI. Wilson is chosen over Clopper-Pearson for reproducibility without
# scipy; the whole report set standardises on it.

from __future__ import annotations

import argparse
import glob
import json
import math
import re
import sys
from pathlib import Path

ROOT = Path("/home/agent-spark/sparkbench")
DEEP = ROOT / "results/deep-eval"

# suite token in the filename -> display name
SUITES = {
    "summarisation": "Summarisation",
    "instruction-following": "Instruction-Following",
    "longcontext": "Long-Context",
}


def wilson_ci(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """Wilson score 95% interval for k successes out of n, returned as percentages."""
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    den = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / den
    margin = (z / den) * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (round(100 * (centre - margin), 1), round(100 * (centre + margin), 1))


def parse_raw(path: Path) -> dict | None:
    """Return {passed, total} from a promptfoo raw JSON, or None if unparseable."""
    try:
        d = json.loads(path.read_text())
        m = d["results"]["prompts"][0]["metrics"]
        passed = int(m["testPassCount"])
        total = passed + int(m["testFailCount"]) + int(m.get("testErrorCount", 0))
        return {"passed": passed, "total": total}
    except Exception as e:  # noqa: BLE001 - any malformed file is a loud skip, recorded
        print(f"WARN: could not parse {path.name}: {e}", file=sys.stderr)
        return None


def collect(prefix: str = "e31-cloud-") -> dict[str, list[dict]]:
    """Collect raw results grouped by suite. Model name is the filename middle segment."""
    out: dict[str, list[dict]] = {v: [] for v in SUITES.values()}
    for f in sorted(DEEP.glob(f"{prefix}*.json")):
        stem = f.stem[len(prefix):]
        suite = next((s for s in SUITES if stem.endswith(s)), None)
        if not suite:
            continue
        model = stem[: -len(suite) - 1]  # strip "-<suite>"
        raw = parse_raw(f)
        if not raw:
            continue
        lo, hi = wilson_ci(raw["passed"], raw["total"])
        pct = round(100 * raw["passed"] / raw["total"], 1) if raw["total"] else 0.0
        out[SUITES[suite]].append(
            {"model": model, "passed": raw["passed"], "total": raw["total"],
             "pct": pct, "ci": (lo, hi), "file": f.name}
        )
    return out


def render(prefix: str) -> str:
    groups = collect(prefix)
    label = "local" if "local" in prefix else "cloud" if "cloud" in prefix else prefix.rstrip("-")
    lines = [
        "<!-- GENERATED by tools/verify_cloud_results.py from the raw promptfoo JSONs.",
        "     DO NOT hand-edit the tables below - regenerate. Wilson 95% score intervals. -->",
        f"# Canonical {label} capability results ({prefix.rstrip('-')}) - generated from raw\n",
    ]
    for suite, rows in groups.items():
        if not rows:
            continue
        lines.append(f"## {suite}\n")
        lines.append("| Model | Passed | Total | Score (Wilson 95% CI) | Raw file |")
        lines.append("|---|---|---|---|---|")
        for r in sorted(rows, key=lambda x: -x["pct"]):
            lines.append(
                f"| {r['model']} | {r['passed']} | {r['total']} | "
                f"{r['pct']:.1f}% (CI {r['ci'][0]:.1f}-{r['ci'][1]:.1f}) | `{r['file']}` |"
            )
        lines.append("")
    return "\n".join(lines)


# Raw filenames sometimes use a role alias for a model (e.g. 'workhorse' == qwen3-30b-a3b).
# Map the normalised alias to the normalised canonical so cross-source matching still lands.
ALIASES = {"workhorse": "qwen330ba3b"}


def _norm(s: str) -> str:
    """Normalise a model name to bare alphanumerics for cross-source matching."""
    return re.sub(r"[^a-z0-9]", "", s.lower())


def _matches(rawm: str, nm: str) -> bool:
    """True if the raw model token (or its alias) appears in the normalised display name."""
    return bool(rawm) and (rawm in nm or ALIASES.get(rawm, "\0") in nm)


_SUITE_HDR = [
    (re.compile(r"summar", re.I), "Summarisation"),
    (re.compile(r"instruction", re.I), "Instruction-Following"),
    (re.compile(r"long.?context", re.I), "Long-Context"),
]


def check(md_path: Path, prefix: str) -> int:
    """Compare '| Model | passed | total | ...' rows against raw, matched by model AND suite.

    Suite is tracked from the nearest '## ...Summarisation/Instruction-Following/Long-Context'
    heading (so a corrupted TOTAL column can't hide a row), the model by normalised-substring.
    Flags any row whose passed OR total disagrees with the raw JSON. This catches both the
    +1 transcription drift (cloud) and the total=passed corruption (local, every score -> 100%).
    """
    # {(normalised_raw_model, suite): (passed, total, file)}
    truth: dict[tuple[str, str], tuple[int, int, str]] = {}
    for suite, rows in collect(prefix).items():
        for r in rows:
            truth[(_norm(r["model"]), suite)] = (r["passed"], r["total"], r["file"])
    mism = 0
    suite = None
    row_re = re.compile(r"^\|\s*([A-Za-z0-9 .()\-/]+?)\s*\|\s*(\d+)\s*\|\s*(\d+)\s*\|")
    for i, line in enumerate(md_path.read_text().splitlines(), 1):
        h = line.strip()
        if h.startswith("#"):
            suite = next((s for rx, s in _SUITE_HDR if rx.search(h)), suite)
            continue
        m = row_re.match(line)
        if not m or suite is None:
            continue
        name, k, n = m.group(1).strip(), int(m.group(2)), int(m.group(3))
        nm = _norm(name)
        match = next((v for (rawm, s), v in truth.items() if s == suite and _matches(rawm, nm)), None)
        if match is None:
            continue  # header/aggregate rows without a model match are not graded
        if (k, n) != (match[0], match[1]):
            print(f"  DRIFT {md_path.name}:{i} [{suite}] '{name}' claims {k}/{n}; "
                  f"raw {match[2]} says {match[0]}/{match[1]}")
            mism += 1
    return mism


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate/verify canonical cloud results from raw JSONs.")
    ap.add_argument("--prefix", default="e31-cloud-", help="raw-file prefix (default: e31-cloud-)")
    ap.add_argument("--check", metavar="MD", help="verify a summary .md's count rows against raw")
    ap.add_argument("--out", metavar="MD", help="write the generated canonical table to this file")
    a = ap.parse_args()
    if a.check:
        n = check(Path(a.check), a.prefix)
        print(f"{'DRIFT DETECTED: ' + str(n) + ' row(s)' if n else 'OK: no count drift vs raw'}")
        sys.exit(1 if n else 0)
    table = render(a.prefix)
    if a.out:
        Path(a.out).write_text(table + "\n")
        print(f"written {a.out}")
    else:
        print(table)


if __name__ == "__main__":
    main()
